"""Index local MP3 files with content hashes; no audio tools or dependencies needed."""
import hashlib
import json
from pathlib import Path
from urllib.parse import quote


def build_audio_manifest(root):
    def describe(path):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        return {
            'url': quote(path.relative_to(root).as_posix(), safe='/') + '?v=' + digest,
            'title': path.stem.partition(' - ')[2] or path.stem,
            'bytes': path.stat().st_size,
        }

    manifest = {'goal': describe(root / 'assets/goal.mp3'), 'chants': {}}
    for club in ['roma', 'lazio']:
        files = sorted((root / 'assets' / ('tracce ' + club)).glob('*.mp3'))
        if not files:
            raise ValueError('Nessun coro trovato per ' + club)
        manifest['chants'][club] = [describe(path) for path in files]
    output = '/* Generated by scripts/build_audio.py. */\n'
    output += 'globalThis.DERBY_AUDIO = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n'
    (root / 'assets/audio-manifest.js').write_text(output, encoding='utf-8')
    return manifest


if __name__ == '__main__':
    manifest = build_audio_manifest(Path(__file__).resolve().parents[1])
    print('Cori indicizzati:', {club: len(tracks) for club, tracks in manifest['chants'].items()})
